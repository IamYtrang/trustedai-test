#!/usr/bin/env python3
"""Replay the README's sample queries as one continuous session per user, writing `results/sample_conversations.md`."""

from __future__ import annotations

import json
import sys
from pathlib import Path

from api.main import build_context

RESULTS_PATH = Path(__file__).resolve().parent.parent / "results" / "sample_conversations.md"

SAMPLE_QUERIES = [
    "What should I watch tonight?",
    "Why do you think I'd like that?",
    "What do people with similar taste to mine think about Pulp Fiction?",
    "I want a dark psychological thriller with a twist",
    "I liked Toy Story but I'm tired of animated movies - what else?",
    "What's my blind spot? What genres am I missing?",
]

TEST_USER_IDS = [1, 15, 30]


def _format_tool_trace(trace: list[dict]) -> str:
    if not trace:
        return "_(no tools called — answered from conversation context alone)_"
    lines = []
    for step in trace:
        result_preview = json.dumps(step["result"])
        if len(result_preview) > 500:
            result_preview = result_preview[:500] + "...(truncated)"
        lines.append(f"- `{step['tool']}({json.dumps(step['arguments'])})`\n  -> `{result_preview}`")
    return "\n".join(lines)


def run_sample_conversations() -> bool:
    context = build_context()
    if context.agent is None:
        print("OPENAI_API_KEY is not set. Set it in .env and re-run.")
        return False

    sections = ["# Sample Conversations\n", "Generated by `evaluation/run_sample_conversations.py`.\n"]

    for user_id in TEST_USER_IDS:
        profile = context.repository.build_user_profile(user_id)
        sections.append(
            f"\n## User {user_id} ({profile.num_ratings} ratings, avg {profile.avg_rating:.2f})\n"
        )
        history = context.agent.initial_messages(user_id)
        for query in SAMPLE_QUERIES:
            print(f"[user {user_id}] {query}")
            result = context.agent.handle_message(history, query)
            history = result["history"]
            sections.append(f"\n**User:** {query}\n")
            sections.append(f"\n**Assistant:** {result['reply']}\n")
            sections.append(f"\n<details><summary>Tool calls</summary>\n\n{_format_tool_trace(result['tool_trace'])}\n\n</details>\n")

    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text("\n".join(sections))
    print(f"\nSaved to {RESULTS_PATH}")
    return True


if __name__ == "__main__":
    sys.exit(0 if run_sample_conversations() else 1)
